import re
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer, ENGLISH_STOP_WORDS
from sklearn.naive_bayes import MultinomialNB
from sklearn.linear_model import LogisticRegression
from sklearn.svm import LinearSVC
from sklearn.metrics import (accuracy_score, precision_score, recall_score, f1_score,
                             confusion_matrix, classification_report, ConfusionMatrixDisplay)
try:
    from nltk.stem import PorterStemmer   # pip install nltk (stemmer needs no extra download)
except ImportError:
    class PorterStemmer:                  # fallback so the notebook still runs without NLTK
        def stem(self, w): return w

sns.set_theme(style="whitegrid")
CSV_PATH = "/content/drive/MyDrive/Colab Notebooks/spam.csv"      # or "SMSSpamCollection"

from google.colab import drive
drive.mount('/content/drive')

"""## 1. Load data and check class distribution"""

try:
    df = pd.read_csv(CSV_PATH, encoding="latin-1")
    df = df[["v1", "v2"]].rename(columns={"v1": "label", "v2": "text"})       # Kaggle format
except KeyError:
    df = pd.read_csv(CSV_PATH, sep="\t", header=None, names=["label", "text"])  # UCI format

df = df.dropna().drop_duplicates().reset_index(drop=True)
df["label_num"] = (df["label"].str.lower() == "spam").astype(int)

print(df.shape)
counts = df["label"].value_counts()
print(pd.DataFrame({"count": counts, "percent": (counts / len(df) * 100).round(2)}))
sns.countplot(data=df, x="label"); plt.title("Spam vs Ham"); plt.show()
df.head()

"""## 2. Text preprocessing pipeline
Lowercase → remove punctuation/numbers → remove stopwords → Porter stemming.
"""

stemmer = PorterStemmer()
stop = set(ENGLISH_STOP_WORDS)

def preprocess(text):
    text = text.lower()
    text = re.sub(r"[^a-z\s]", " ", text)           # drop punctuation and digits
    tokens = [w for w in text.split() if w not in stop and len(w) > 1]
    return " ".join(stemmer.stem(w) for w in tokens)

df["clean"] = df["text"].apply(preprocess)
df[["text", "clean"]].head()

"""## 3. Feature extraction with TF-IDF

**What does TF-IDF measure?** TF-IDF (*Term Frequency - Inverse Document Frequency*) scores how important a word is to a message relative to the whole collection.
- **TF** = how often the word appears in this message.
- **IDF** = `log(N / df)`, which down-weights words that appear in many messages (like "u" or "call") and up-weights rare, distinctive ones (like "prize" or "claim").

The product gives high scores to words that are frequent in one message but rare overall, which is exactly what separates spam from ham.
"""

X_train_txt, X_test_txt, y_train, y_test = train_test_split(
    df["clean"], df["label_num"], test_size=0.2, random_state=42, stratify=df["label_num"])

tfidf = TfidfVectorizer(ngram_range=(1, 2), min_df=2, max_features=10000)
X_train = tfidf.fit_transform(X_train_txt)    # fit ONLY on training data to avoid leakage
X_test = tfidf.transform(X_test_txt)
print("TF-IDF matrix:", X_train.shape)

"""## 4. Train and evaluate classifiers"""

models = {
    "Multinomial Naive Bayes": MultinomialNB(alpha=0.1),
    "Logistic Regression": LogisticRegression(max_iter=1000, class_weight="balanced"),
    "Linear SVM": LinearSVC(class_weight="balanced"),
}
rows, preds = [], {}
for name, m in models.items():
    m.fit(X_train, y_train)
    p = m.predict(X_test); preds[name] = p
    rows.append({"Model": name,
                 "Accuracy": accuracy_score(y_test, p),
                 "Precision": precision_score(y_test, p),
                 "Recall": recall_score(y_test, p),
                 "F1": f1_score(y_test, p)})
    print("=" * 60); print(name); print(classification_report(y_test, p, target_names=["ham", "spam"]))
    ConfusionMatrixDisplay(confusion_matrix(y_test, p), display_labels=["ham", "spam"]).plot(cmap="Blues")
    plt.title(name); plt.show()

results = pd.DataFrame(rows).set_index("Model").sort_values("F1", ascending=False)
display(results.round(4))
print("Best model by F1:", results.index[0])

"""## 5. Why is recall important for spam detection?
**Recall = TP / (TP + FN)** is the share of all real spam that we actually catch. A low recall means many spam messages slip into the inbox, which exposes users to phishing, scams and malware links - the exact problem a spam filter exists to solve.

There is a trade-off, though: pushing recall up can lower **precision** and wrongly send genuine ("ham") messages to the spam folder, which can be costly (missed OTPs, job offers). So in practice we want high recall while keeping precision very high, and the **F1 score** balances the two.

## 6. Test on new messages
"""

best_model = models[results.index[0]]
samples = ["Congratulations! You won a free prize. Call now to claim your reward",
           "Hey, are we still meeting for lunch tomorrow?",
           "URGENT! Your account is blocked. Click the link to verify"]
pred = best_model.predict(tfidf.transform([preprocess(s) for s in samples]))
for s, p in zip(samples, pred):
    print("SPAM" if p else "HAM ", "|", s)

